/**
 * Development tool: `npm run fixtures:capture -- <store> <product url> <case>`.
 *
 * Fetches the store's catalog request(s) through the same FetchContext as
 * production (allowlist, robots.txt, 1 request/s, User-Agent), trims the
 * response to the fields the adapter uses and saves it under
 * test/fixtures/<store>/<case>.json together with an expected.json skeleton
 * derived from the adapter. Review the skeleton by hand before committing.
 *
 * It makes real network requests: run it rarely and only on purpose.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { createStoreFetchContext } from '../src/http/context.js';
import { stores } from '../src/stores/index.js';
import { trimCatalog } from '../src/stores/vtex/trim.js';
import { fixtureContext, jsonOk } from '../test/helpers/fixture-context.js';

const CASE_NAME = /^[a-z0-9-]{1,60}$/;

/**
 * @param {string[]} args
 * @returns {Promise<number>} exit code
 */
async function main(args) {
  const [storeId, productUrl, caseName] = args;
  const store = stores.find((candidate) => candidate.id === storeId);
  if (store === undefined || productUrl === undefined || caseName === undefined || !CASE_NAME.test(caseName)) {
    console.error(`usage: npm run fixtures:capture -- <${stores.map((s) => s.id).join('|')}> <product url> <case-name>`);
    return 2;
  }

  const url = new URL(productUrl);
  const check = store.validateUrl(url);
  if (!check.ok || !store.hosts.includes(url.hostname)) {
    console.error(`not a valid ${store.id} product URL: ${check.ok ? 'host' : check.reason}`);
    return 2;
  }

  const targets = store.captureUrls(url);
  if (targets.length !== 1) {
    console.error('this store needs more than one request per fixture; not supported by the tool yet');
    return 2;
  }

  const ctx = createStoreFetchContext(stores, { log: (message) => console.warn(message) });
  const target = /** @type {string} */ (targets[0]);
  console.log(`GET ${target}`);
  const response = await ctx.get(target, { accept: 'application/json' });
  if (!response.ok) {
    console.error(`capture failed: ${response.kind} (${response.detail})`);
    return 1;
  }

  const trimmed = trimCatalog(response.body);
  const directory = new URL(`../test/fixtures/${store.id}/`, import.meta.url);
  mkdirSync(directory, { recursive: true });
  writeFileSync(new URL(`${caseName}.json`, directory), trimmed);

  const { ctx: replay } = fixtureContext(jsonOk(trimmed));
  const { outcome, failure, listaCents, contado, tarjetas } = await store.measure(replay, productUrl, { codigoPostal: '5000' });
  const skeleton = { _note: 'Skeleton generated by fixtures:capture from the adapter output: verify every value by hand against the store, then remove this key.', outcome, failure, listaCents, contado, tarjetas };
  writeFileSync(new URL(`${caseName}.expected.json`, directory), `${JSON.stringify(skeleton, null, 2)}\n`);

  console.log(`saved test/fixtures/${store.id}/${caseName}.json (${trimmed.length} bytes) and ${caseName}.expected.json; requests made: ${ctx.requestCount()} (robots.txt included)`);
  return 0;
}

process.exitCode = await main(process.argv.slice(2));
